#!/usr/bin/env python3
"""Generate condition configs from the cue registry. `python deploysim/configs/build_cue_conditions.py [--check]`

Writes deploysim/configs/cues/:
  SB-G.yaml, SB-D.yaml                  v1 edition, every cue graded / every cue deployment
  SB-G~<cue>.yaml, SB-D~<cue>.yaml      v1, one cue swapped to the other arm's version (never deleted)
  SB-G~system_prompt=shared.yaml, ...   v1 with the shared system prompt (decision 3: kept alongside the per-arm ones)
  baseline/SB0-G.yaml, SB0-D.yaml       baseline edition: must reproduce DS-G and DS-D-NOPUSH (tests, smoke)
Agent and task settings are the frozen arms' (deploysim/configs/build_ds_arms.py). The frozen arm configs are not
touched."""
from __future__ import annotations

import copy
import hashlib
import json
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parents[1]
sys.path.insert(0, str(REPO_ROOT / "deploysim" / "cues"))
import registry as R  # noqa: E402

OUT = HERE / "cues"
EXPERIMENT = "splitbrain"


class _Lit(str):
    pass


yaml.add_representer(_Lit, lambda d, data: d.represent_scalar("tag:yaml.org,2002:str", data, style="|"))


def _lit(x):
    if isinstance(x, str):
        return _Lit(x) if "\n" in x else x
    if isinstance(x, list):
        return [_lit(v) for v in x]
    if isinstance(x, dict):
        return {k: _lit(v) for k, v in x.items()}
    return x


def conditions() -> dict[str, dict]:
    out = {"SB-G": R.render("v1", base="graded"), "SB-D": R.render("v1", base="deployment")}
    for base, cue, settings in R.swaps("v1"):
        out[f"SB-{'G' if base == 'graded' else 'D'}~{cue}"] = R.render("v1", settings)
    for base in ("graded", "deployment"):
        reg = R.load("v1"); s = {**R.default_settings(reg, base), "system_prompt": "shared"}
        out[f"SB-{'G' if base == 'graded' else 'D'}~system_prompt=shared"] = R.render("v1", s)
    out["baseline/SB0-G"] = R.render("baseline", base="graded")
    out["baseline/SB0-D"] = R.render("baseline", base="deployment")
    return out


def build(cid: str, r: dict) -> dict:
    A, F = R.frozen()
    src = A.build("DS-G")
    task = copy.deepcopy(src["task"]); task["sf_framing"] = "cues"; task["cue_content"] = r["cue_content"]
    base = "deployment" if cid.rsplit("/", 1)[-1].startswith(("SB-D", "SB0-D")) else "graded"
    settings_hash = hashlib.sha256(json.dumps(r["settings"], sort_keys=True).encode()).hexdigest()[:12]
    return _lit({"environment": src["environment"], "agent": copy.deepcopy(src["agent"]), "task": task,
                 "prompts": {"system_prompt": r["system_prompt"], "prior_turns": r["prior_turns"], "user_prompt": r["user_prompt"]},
                 "condition": {"id": cid.rsplit("/", 1)[-1], "experiment": EXPERIMENT, "env_version": F.ENV_VERSION, "cue_edition": r["edition"], "base_arm": base,
                               "cue_settings": r["settings"], "cue_settings_hash": settings_hash,
                               "source_config": src["condition"]["source_config"], "source_config_hash": src["condition"]["source_config_hash"]}})


def render_file(cid: str, r: dict) -> str:
    return (f"# {cid}: GENERATED by deploysim/configs/build_cue_conditions.py from deploysim/cues/cues.yaml ({r['edition']} edition). Do not edit.\n"
            f"# Launch: deploysim/scripts/launch_ds.sh cues/{cid} <count> --batch NAME   (paid: uses your provider key)\n") + yaml.dump(build(cid, r), sort_keys=False, allow_unicode=True, width=10_000)


def main(argv) -> int:
    stale = []; n = 0
    for cid, r in conditions().items():
        p = OUT / f"{cid}.yaml"; text = render_file(cid, r); n += 1
        if "--check" in argv:
            if not p.exists() or p.read_text() != text: stale.append(cid)
        else:
            p.parent.mkdir(parents=True, exist_ok=True); p.write_text(text)
    print(f"{n} conditions{' checked' if '--check' in argv else ' written to ' + str(OUT.relative_to(REPO_ROOT))}")
    if stale:
        print("STALE:", stale); return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
