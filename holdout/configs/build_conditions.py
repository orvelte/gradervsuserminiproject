#!/usr/bin/env python3
"""Write holdout condition configs: `python holdout/configs/build_conditions.py [--check]`.

  HO-{G,D}~{visible,holdout,none}.yaml   frame × scoring variant (spec §5)
Agent settings are the deploysim frozen arms' (GPT-OSS-120B, akashml/bf16, reasoning high) with max_steps 60; other
models by override (agent.model=... agent.provider_preferences=null), as in deploysim.
"""
from __future__ import annotations

import copy
import hashlib
import json
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
sys.path.insert(0, str(REPO / "holdout" / "cues")); sys.path.insert(0, str(REPO / "deploysim" / "configs"))
import render as R  # noqa: E402
import build_ds_arms as A  # noqa: E402

MAX_STEPS = 100   # ho-1.1: 60 cut off GLM runs that cross-validated (H1)
ENV_VERSION = "ho-1.1"   # 1.1: data v2 (realistic ticket text)


class _Lit(str):
    pass


yaml.add_representer(_Lit, lambda d, data: d.represent_scalar("tag:yaml.org,2002:str", data, style="|"))


def _lit(x):
    if isinstance(x, str):
        return _Lit(x) if "\n" in x else x
    if isinstance(x, list):
        return [_lit(v) for v in x]
    if isinstance(x, dict):
        return {k: _lit(v) for k, v in x.items()}
    return x


def conditions() -> dict:
    return {f"HO-{'G' if f == 'graded' else 'D'}~{s}": (f, s, R.render(f, s)) for f in R.FRAMES for s in R.SCORING}


def build(cid: str, frame: str, scoring: str, r: dict) -> dict:
    agent = copy.deepcopy(A.build("DS-G")["agent"]); agent["max_steps"] = MAX_STEPS
    h = hashlib.sha256(json.dumps(r["settings"], sort_keys=True).encode()).hexdigest()[:12]
    return _lit({"environment": "holdout", "agent": agent,
                 "task": {"tools": ["bash", "apply_patch", "ask_question"], "sf_framing": "cues", "scoring_variant": scoring, "cue_content": r["cue_content"]},
                 "prompts": {"system_prompt": r["system_prompt"], "prior_turns": r["prior_turns"], "user_prompt": r["user_prompt"]},
                 "condition": {"id": cid, "experiment": "holdout", "env_version": ENV_VERSION, "frame": frame, "scoring": scoring, "cue_edition": r["edition"],
                               "cue_settings": r["settings"], "cue_settings_hash": h}})


def text(cid, frame, scoring, r) -> str:
    return (f"# {cid}: GENERATED by holdout/configs/build_conditions.py from holdout/cues/cues.yaml. Do not edit.\n"
            f"# Launch: holdout/scripts/launch_ho.sh {cid} <count> --batch NAME   (paid: uses your provider key)\n") + yaml.dump(build(cid, frame, scoring, r), sort_keys=False, allow_unicode=True, width=10_000)


def main(argv) -> int:
    stale = []
    for cid, (f, s, r) in conditions().items():
        p = HERE / f"{cid}.yaml"; t = text(cid, f, s, r)
        if "--check" in argv:
            if not p.exists() or p.read_text() != t:
                stale.append(cid)
        else:
            p.write_text(t)
    print(f"{len(conditions())} conditions {'checked' if '--check' in argv else 'written'}")
    if stale:
        print("STALE:", stale); return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
