#!/usr/bin/env python3
"""PP2-E episode configs (PREREG PP2): HO-D~visible with a persona appended to the system prompt, five conditions.

    python internals/personaprompt/pp2_configs.py            # writes holdout/configs/pp2/*.yaml and pp2/smoke/*.yaml

The persona texts come from internals/personaprompt/pp2_personas.json (frozen from the PP1 finalists and candidates;
regenerate with --refresh-personas, which reads results/personaprompt/). The persona is appended to the system prompt
as "\\n\\n" + text, exactly as forced_choice.render does; nothing else differs from HO-D~visible. Launch like V1:
    holdout/scripts/launch_ho.sh pp2/HO-D~visible+rule1 20 --batch pp2_qwen38 --max-concurrent 12 \\
        agent.provider=vllm_completions agent.model=qwen3.8-27b agent.provider_preferences=null
The smoke variants use the mock provider (no key, no cost) to check that the text reaches the agent's system message.
"""
from __future__ import annotations

import copy
import hashlib
import json
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
BASE = REPO / "holdout" / "configs" / "HO-D~visible.yaml"
OUT = REPO / "holdout" / "configs" / "pp2"
PERSONAS = HERE / "pp2_personas.json"
ORDER = ["none", "rule1", "rule5", "char1", "servant"]


def refresh_personas() -> dict:
    R = REPO / "results" / "personaprompt"
    fin = json.loads((R / "finalists.json").read_text())["finalists"]
    rules = [r for r in fin if r["cls"] == "rule"]; chars = [r for r in fin if r["cls"] == "character"]
    allc = json.loads((R / "semantic_leaks_all_characters.json").read_text())
    servant = max((a for a in allc if a.get("flagged") is False), key=lambda a: a["fitness"])
    p = {"none": None, "rule1": rules[0]["text"], "rule5": rules[4]["text"], "char1": chars[0]["text"], "servant": servant["text"]}
    assert p["rule5"].startswith("Overfit decisively"), p["rule5"]
    assert p["servant"].startswith("You are a loyal servant"), p["servant"]
    PERSONAS.write_text(json.dumps(p, indent=1) + "\n")
    return p


class Lit(str):
    pass


yaml.add_representer(Lit, lambda d, data: d.represent_scalar("tag:yaml.org,2002:str", data, style="|" if "\n" in data else None))


def _lit(x):
    if isinstance(x, dict):
        return {k: _lit(v) for k, v in x.items()}
    if isinstance(x, list):
        return [_lit(v) for v in x]
    return Lit(x) if isinstance(x, str) else x


def build(personas: dict) -> list[Path]:
    base = yaml.safe_load(BASE.read_text()); out = []
    (OUT / "smoke").mkdir(parents=True, exist_ok=True)
    for name in ORDER:
        text = personas[name]; cfg = copy.deepcopy(base)
        if text:
            cfg["prompts"]["system_prompt"] = cfg["prompts"]["system_prompt"] + "\n\n" + text.strip()
        cfg["condition"]["id"] = f"HO-D~visible+{name}"
        cfg["condition"]["persona"] = name
        cfg["condition"]["persona_sha"] = hashlib.sha256((text or "").encode()).hexdigest()[:12]
        head = (f"# HO-D~visible+{name}: GENERATED by internals/personaprompt/pp2_configs.py (PREREG PP2-E). Do not edit.\n"
                f"# HO-D~visible with the persona appended to the system prompt; launch with the V1 provider overrides.\n")
        p = OUT / f"HO-D~visible+{name}.yaml"; p.write_text(head + yaml.dump(_lit(cfg), sort_keys=False, allow_unicode=True, width=120)); out.append(p)
        smoke = copy.deepcopy(cfg)
        smoke["agent"] = {"provider": "mock", "model": "mock", "max_steps": 5, "reasoning_effort": "high", "llm_heal": False,
                          "mock_script": [{"command": "ls && ./score | head -3", "reasoning": "Look around."},
                                          {"reasoning": "Done.", "content": "Done."}]}
        smoke["condition"]["id"] += "~smoke"
        (OUT / "smoke" / f"HO-D~visible+{name}.yaml").write_text("# mock smoke variant (no key, no cost)\n" + yaml.dump(_lit(smoke), sort_keys=False, allow_unicode=True, width=120))
    return out


if __name__ == "__main__":
    ps = refresh_personas() if "--refresh-personas" in sys.argv or not PERSONAS.exists() else json.loads(PERSONAS.read_text())
    for p in build(ps):
        print(p.relative_to(REPO))
